    def prime_number(self):
        n = int(input("Enter a number? "))

        prime = True

        if n < 2:
            prime = False
        else:
            for i in range(2, n):
                if n % i == 0:
                    prime = False
                    break

        if prime:
            print(n, "is a prime number")
        else:
            print(n, "is NOT a prime number")


    # Ex 4
    def perfect_number(self):
        n = int(input("Enter a number? "))

        found = False

        for p in range(2, n):
            p_prime = True

            for i in range(2, p):
                if p % i == 0:
                    p_prime = False
                    break

            if p_prime:
                m = 2 ** p - 1
                m_prime = True

                for i in range(2, m):
                    if m % i == 0:
                        m_prime = False
                        break

                if m_prime and 2 ** (p - 1) * m == n:
                    found = True
                    break

        if found:
            print(n, "is a perfect number")
        else:
            print(n, "is NOT a perfect number")


