class Student:
    def __init__(self, id, name, dob):
        self.id = id
        self.name = name
        self.dob = dob


class Course:
    def __init__(self, id, name):
        self.id = id
        self.name = name


class StudentManagement:
    def __init__(self):
        self.students = {}
        self.courses = {}
        self.marks = {}

    def add_students(self):
        n = int(input("Number of students: "))

        for i in range(n):
            id = input("ID: ")
            name = input("Name: ")
            dob = input("DoB: ")

            self.students[id] = Student(id, name, dob)

    def add_courses(self):
        n = int(input("Number of courses: "))

        for i in range(n):
            id = input("Course ID: ")
            name = input("Course name: ")

            self.courses[id] = Course(id, name)

    def add_marks(self):
        course = input("Course ID: ")

        if course not in self.courses:
            print("This course doesn't exist. Please choose again!")
            return

        if course not in self.marks:
            self.marks[course] = {}

        for id in self.students:
            mark = input("Mark for " + self.students[id].name + ": ")
            self.marks[course][id] = mark

    def show_students(self):
        for id in self.students:
            student = self.students[id]
            print(student.id, student.name, student.dob)

    def show_courses(self):
        for id in self.courses:
            course = self.courses[id]
            print(course.id, course.name)

    def show_marks(self):
        while True:
            course = input("Course ID: ")

            if course not in self.courses:
                print("This course doesn't exist. Please choose again!")
                continue

            if course not in self.marks:
                print("This course hasn't been marked yet. Please choose again!")
                continue

            print("Course:", self.courses[course].name)

            for id in self.marks[course]:
                print(
                    self.students[id].name,
                    ":",
                    self.marks[course][id]
                )

            break


